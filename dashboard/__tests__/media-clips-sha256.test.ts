import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { runClipChecksumLists } from '../lib/media/clips-sha256';

const repo = path.resolve(__dirname, '../..');

describe('clip SHA-256 lists', () => {
    it('writes stable sorted lists, checks differences, and leaves clips unchanged', () => {
        const root = fs.mkdtempSync(path.join(os.tmpdir(), 'clips-sha256-'));
        const primaryRoot = path.join(root, 'content/primary');
        const storytimeRoot = path.join(root, 'content/storytime');
        const book = path.join(primaryRoot, 'quest-6.1');
        const lesson = path.join(book, 'media/l09/.clips');
        fs.mkdirSync(lesson, { recursive: true });
        fs.copyFileSync(path.join(repo, 'content/primary/quest-6.1/l09.json'), path.join(book, 'l09.json'));
        for (const name of ['b.opus', 'a.opus', 'c.opus']) fs.writeFileSync(path.join(lesson, name), `fixture:${name}`);
        const before = Object.fromEntries(fs.readdirSync(lesson).map((name) => [name, fs.readFileSync(path.join(lesson, name))]));
        const level = path.join(storytimeRoot, 'l2');
        fs.mkdirSync(path.join(level, 'media'), { recursive: true });
        const week = fs.readFileSync(path.join(repo, 'content/storytime/l2/w01.json'));
        for (let i = 1; i <= 7; i++) {
            const name = `w0${i}`;
            fs.writeFileSync(path.join(level, `${name}.json`), week);
            fs.mkdirSync(path.join(level, 'media', name, '.clips'), { recursive: true });
        }
        const run = (mode: 'write' | 'check') => runClipChecksumLists({ primaryRoot, storytimeRoot, mode });
        expect(run('write').differences).toEqual([]);
        const list = path.join(book, 'media/clips.sha256');
        const first = fs.readFileSync(list, 'utf8');
        expect(run('write').differences).toEqual([]);
        expect(fs.readFileSync(list, 'utf8')).toBe(first);
        for (const [name, bytes] of Object.entries(before)) expect(fs.readFileSync(path.join(lesson, name))).toEqual(bytes);
        const lines = first.trimEnd().split('\n');
        expect(lines[0]).toBe('# lesson\tkey\ttype\tbytes\tsha256 (generated by: cd dashboard && npx tsx scripts/media/clips-sha256.ts)');
        expect(lines.slice(1).map((line) => line.split('\t')[1])).toEqual(['a', 'b', 'c']);
        expect(lines.slice(1).every((line) => /^l09\t[a-c]\torphan\t\d+\t[0-9a-f]{64}$/.test(line))).toBe(true);
        expect(run('check').differences).toEqual([]);
        fs.writeFileSync(path.join(lesson, 'a.opus'), 'changed');
        expect(run('check').differences.join('\n')).toContain('changed l09/a');
        fs.unlinkSync(path.join(lesson, 'b.opus'));
        expect(run('check').differences.join('\n')).toContain('missing l09/b');
        fs.writeFileSync(path.join(lesson, 'd.opus'), 'added');
        expect(run('check').differences.join('\n')).toContain('extra l09/d');
        for (const [name, bytes] of Object.entries(before)) {
            if (name !== 'a.opus' && name !== 'b.opus') expect(fs.readFileSync(path.join(lesson, name))).toEqual(bytes);
        }
        fs.rmSync(root, { recursive: true, force: true });
    });
});

import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { LessonPackageSchema } from '../lesson-package/schema';
import { audioClips, clipKey, flashcardSentences, voicesFor } from './audio';
import { tutorClips, tutorItems } from './tutor-audio';
import { BOOK_SPEEDS, bookSentences } from '../storytime/book-audio';
import { StorytimeWeekSchema } from '../storytime/schema';

export interface ClipListOptions {
    primaryRoot: string;
    storytimeRoot: string;
    mode: 'write' | 'check';
}

interface CacheEntry {
    lesson: string;
    key: string;
    type: string;
    bytes: number;
    sha256: string;
}

const HEADER = '# lesson\tkey\ttype\tbytes\tsha256 (generated by: cd dashboard && npx tsx scripts/media/clips-sha256.ts)';
const digest = (file: string) => createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const filesIn = (dir: string) => fs.existsSync(dir) ? fs.readdirSync(dir).filter((name) => fs.statSync(path.join(dir, name)).isFile()).sort() : [];

function primaryUses(bookDir: string): Map<string, Map<string, string[]>> {
    const uses = new Map<string, Map<string, string[]>>();
    const addUse = (lesson: string, type: string, text: string, voice: string, speed: number) => {
        const key = clipKey(text, voice, speed);
        const byKey = uses.get(lesson) ?? new Map<string, string[]>();
        byKey.set(key, [...(byKey.get(key) ?? []), type]);
        uses.set(lesson, byKey);
    };
    for (const packageFile of fs.readdirSync(bookDir).filter((name) => /^(?:l\d\d|p\d\d|b\d{3})\.json$/.test(name)).sort()) {
        const lesson = path.basename(packageFile, '.json');
        const pkg = LessonPackageSchema.parse(JSON.parse(fs.readFileSync(path.join(bookDir, packageFile), 'utf8')));
        const raw = JSON.parse(fs.readFileSync(path.join(bookDir, packageFile), 'utf8')) as { audio?: { speed?: unknown } };
        const speed = typeof raw.audio?.speed === 'number' && Number.isFinite(raw.audio.speed) ? raw.audio.speed : 0.75;
        const voices = voicesFor(pkg);
        const clips = audioClips(pkg);
        clips.article.forEach((clip) => addUse(lesson, 'article', clip.text, voices.narrator, speed));
        clips.words.forEach((clip) => addUse(lesson, 'word', clip.text, voices.teacher, speed));
        flashcardSentences(pkg).forEach((text) => addUse(lesson, 'article', text, voices.narrator, speed));
        if (pkg.meta.role !== 'bank') for (const clip of tutorClips(tutorItems(pkg))) {
            const prefix = clip.id.split('-')[0];
            const detail = clip.id.includes('-option') ? 'option' : clip.kind === 'question' ? 'question' : '';
            addUse(lesson, `tutor:${detail ? `${prefix}-${detail}` : clip.kind}`, clip.text, clip.role === 'narrator' ? voices.narrator : voices.teacher, speed);
        }
    }
    return uses;
}

function primaryBookList(bookDir: string, allUsedKeys: Set<string>): string {
    const uses = primaryUses(bookDir);
    const media = path.join(bookDir, 'media');
    const rows: CacheEntry[] = [];
    for (const lesson of fs.existsSync(media) ? fs.readdirSync(media).sort() : []) {
        const cache = path.join(media, lesson, '.clips');
        for (const file of filesIn(cache)) {
            const key = path.basename(file, path.extname(file));
            const matched = uses.get(lesson)?.get(key) ?? [];
            const type = matched.includes('article') ? 'article' : matched.includes('word') ? 'word' : matched.find((value) => value.startsWith('tutor:')) ?? (matched.length ? matched[0] : allUsedKeys.has(key) ? 'lesson-orphan' : 'orphan');
            const fullPath = path.join(cache, file);
            rows.push({ lesson, key, type, bytes: fs.statSync(fullPath).size, sha256: digest(fullPath) });
        }
    }
    return serialize(rows);
}

function storytimeList(storytimeRoot: string): string {
    const levelDir = path.join(storytimeRoot, 'l2');
    const rows: CacheEntry[] = [];
    const weeks = fs.readdirSync(path.join(levelDir, 'media')).filter((name) => /^w0[1-7]$/.test(name)).sort();
    const weekUses = new Map<string, Set<string>>();
    const contents = new Map<string, string[]>();
    for (const weekName of weeks) {
        const weekFile = path.join(levelDir, `${weekName}.json`);
        const week = StorytimeWeekSchema.parse(JSON.parse(fs.readFileSync(weekFile, 'utf8')));
        const needed = new Map<string, string>();
        for (const book of week.books) for (const sentence of bookSentences(book)) {
            const voice = book.audio.voice ?? 'English_captivating_female1';
            for (const speed of Object.values(BOOK_SPEEDS)) needed.set(clipKey(sentence.text, voice, speed), 'article');
        }
        contents.set(weekName, [...needed.keys()]);
        for (const key of needed.keys()) weekUses.set(key, new Set([...(weekUses.get(key) ?? []), weekName]));
    }
    for (const weekName of weeks) {
        const cache = path.join(levelDir, 'media', weekName, '.clips');
        for (const file of filesIn(cache)) {
            const fullPath = path.join(cache, file);
            const key = path.basename(file);
            const opusKey = key.replace(/\.opus$/, '');
            const type = key.endsWith('.words.json') ? 'words' : contents.get(weekName)?.includes(opusKey) ? 'article' : weekUses.has(opusKey) ? 'lesson-orphan' : 'orphan';
            rows.push({ lesson: weekName, key, type, bytes: fs.statSync(fullPath).size, sha256: digest(fullPath) });
        }
    }
    return serialize(rows);
}

function serialize(rows: CacheEntry[]): string {
    return [HEADER, ...rows.sort((a, b) => a.lesson.localeCompare(b.lesson) || a.key.localeCompare(b.key)).map((row) => [row.lesson, row.key, row.type, row.bytes, row.sha256].join('\t'))].join('\n') + '\n';
}

function compareList(expected: string, actual: string, label: string): string[] {
    const differences = expected.split('\n', 1)[0] === actual.split('\n', 1)[0] ? [] : [`${label}: changed header`];
    const expectedRows = new Map(expected.split('\n').slice(1).filter(Boolean).map((line) => [line.split('\t').slice(0, 2).join('\t'), line]));
    const actualRows = new Map(actual.split('\n').slice(1).filter(Boolean).map((line) => [line.split('\t').slice(0, 2).join('\t'), line]));
    differences.push(...[...new Set([...expectedRows.keys(), ...actualRows.keys()])].sort().flatMap((key) => {
        if (!expectedRows.has(key)) return [`${label}: extra ${key.replace('\t', '/')}`];
        if (!actualRows.has(key)) return [`${label}: missing ${key.replace('\t', '/')}`];
        return expectedRows.get(key) === actualRows.get(key) ? [] : [`${label}: changed ${key.replace('\t', '/')}`];
    }));
    return differences;
}

/** Builds or checks all per-book clip checksum lists. */
export function runClipChecksumLists(options: ClipListOptions): { files: number; differences: string[] } {
    const books = fs.readdirSync(options.primaryRoot).filter((book) => fs.existsSync(path.join(options.primaryRoot, book, 'media'))).sort();
    const allUsedKeys = new Set(books.flatMap((book) => [...primaryUses(path.join(options.primaryRoot, book)).values()].flatMap((keys) => [...keys.keys()])));
    const targets = books.map((book) => ({ file: path.join(options.primaryRoot, book, 'media', 'clips.sha256'), content: primaryBookList(path.join(options.primaryRoot, book), allUsedKeys) }));
    targets.push({ file: path.join(options.storytimeRoot, 'l2', 'media', 'clips.sha256'), content: storytimeList(options.storytimeRoot) });
    let files = 0;
    const differences: string[] = [];
    for (const target of targets) {
        const existing = fs.existsSync(target.file) ? fs.readFileSync(target.file, 'utf8') : '';
        if (options.mode === 'check') {
            const diff = compareList(existing, target.content, path.relative(process.cwd(), target.file));
            differences.push(...diff);
            files += target.content.split('\n').length - 2;
        } else {
            const temp = `${target.file}.tmp`;
            fs.writeFileSync(temp, target.content);
            fs.renameSync(temp, target.file);
            files += target.content.split('\n').length - 2;
        }
    }
    return { files, differences };
}

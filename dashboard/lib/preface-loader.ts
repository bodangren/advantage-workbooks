export function getPrefaceByCefrLevel(cefrLevel: string | null | undefined): PrefaceData | null {
  if (!cefrLevel) {
    return null;
  }

  const normalizedLevel = cefrLevel.toUpperCase().trim();
  
  if (PREFACE_DATA[normalizedLevel]) {
    return PREFACE_DATA[normalizedLevel];
  }

  if (normalizedLevel === 'PRE-A1') {
    return PREFACE_DATA['A1'];
  }

  return null;
}
